def _pixmap(name: str, color: str, size: int, dpr: int = 2) -> QPixmap:
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
           f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{_PATHS[name]}</svg>')
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    pm = QPixmap(size * dpr, size * dpr)
    pm.setDevicePixelRatio(dpr)
    pm.fill(Qt.GlobalColor.transparent)
    p = QPainter(pm)
    renderer.render(p, QRectF(0, 0, size, size))
    p.end()
    return pm


def nav_icon(name: str, size: int = 20) -> QIcon:
    """Icono con estado normal (gris) y marcado (azul neón), para botones checkables."""
    t = theme.current()
    icon = QIcon()
    icon.addPixmap(_pixmap(name, t["muted"], size), QIcon.Mode.Normal, QIcon.State.Off)
    icon.addPixmap(_pixmap(name, t["accent2"], size), QIcon.Mode.Normal, QIcon.State.On)
    icon.addPixmap(_pixmap(name, t["text"], size), QIcon.Mode.Active, QIcon.State.Off)
    return icon


def icon(name: str, color_key: str = "text", size: int = 18) -> QIcon:
    return QIcon(_pixmap(name, theme.current()[color_key], size))
